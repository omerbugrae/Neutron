'use strict';

const { spawnSync } = require('node:child_process');
const fs = require('node:fs');
const path = require('node:path');
const { MakerBase } = require('@electron-forge/maker-base');

function locateMakeNsis() {
  const candidates = [
    process.env.NSIS_HOME && path.join(process.env.NSIS_HOME, 'makensis.exe'),
    'C:\\Program Files (x86)\\NSIS\\makensis.exe',
    'C:\\Program Files\\NSIS\\makensis.exe',
  ].filter(Boolean);
  for (const candidate of candidates) {
    if (fs.existsSync(candidate)) return candidate;
  }
  const fromPath = spawnSync('where.exe', ['makensis.exe'], { encoding: 'utf8', windowsHide: true });
  if (fromPath.status === 0) {
    const first = String(fromPath.stdout).split(/\r?\n/).find(Boolean);
    if (first) return first.trim();
  }
  throw new Error(
    'NSIS makensis.exe bulunamadı. NSIS 3.x kurun veya NSIS_HOME ortam değişkenini NSIS klasörüne ayarlayın.',
  );
}

function toFileVersion(version) {
  const numbers = String(version)
    .split(/[+-]/, 1)[0]
    .split('.')
    .map((part) => Number.parseInt(part, 10))
    .map((part) => (Number.isFinite(part) && part >= 0 ? Math.min(part, 65535) : 0));
  while (numbers.length < 4) numbers.push(0);
  return numbers.slice(0, 4).join('.');
}

function nsisEscape(value) {
  return String(value).replace(/\$/g, '$$').replace(/"/g, '$\\"');
}

function collectInstalledPaths(root) {
  const files = [];
  const directories = [];
  function visit(directory) {
    for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
      const absolute = path.join(directory, entry.name);
      const relative = path.relative(root, absolute).replace(/\//g, '\\');
      if (entry.isDirectory()) {
        visit(absolute);
        directories.push(relative);
      } else if (entry.isFile()) {
        files.push(relative);
      }
    }
  }
  visit(root);
  return { files, directories };
}

function writeUninstallManifest(appDirectory, manifestPath) {
  const { files, directories } = collectInstalledPaths(appDirectory);
  const lines = [
    '; Generated by tools/forge-maker-nsis.cjs. Do not edit.',
    ...files.map((relative) => `Delete \"$INSTDIR\\${nsisEscape(relative)}\"`),
    ...directories.map((relative) => `RMDir \"$INSTDIR\\${nsisEscape(relative)}\"`),
    '',
  ];
  fs.writeFileSync(manifestPath, lines.join('\r\n'));
}

function assertNoBundledModelArtifacts(appDirectory) {
  const { files } = collectInstalledPaths(appDirectory);
  const forbidden = files.filter((relative) => {
    const normalized = relative.replace(/\\/g, '/').toLowerCase();
    return normalized.endsWith('.model')
      || normalized.endsWith('.nfchunk')
      || normalized.includes('/feature-dist/');
  });
  if (forbidden.length) {
    throw new Error(
      `Model dosyaları kurucu paketine giremez. Bulunan ilk dosya: ${forbidden[0]}`,
    );
  }
}

class MakerNsis extends MakerBase {
  constructor(...args) {
    super(...args);
    this.name = 'nsis';
    this.defaultPlatforms = ['win32'];
  }

  isSupportedOnCurrentPlatform() {
    return process.platform === 'win32';
  }

  async make({ dir, makeDir, targetArch, packageJSON, appName }) {
    const makeNsis = locateMakeNsis();
    const outputDirectory = path.resolve(makeDir, 'nsis', targetArch);
    await this.ensureDirectory(outputDirectory);
    const manifestPath = path.join(outputDirectory, 'uninstall-files.nsh');
    const outputPath = path.join(outputDirectory, `${appName}-${packageJSON.version}-${targetArch}-Setup.exe`);
    assertNoBundledModelArtifacts(dir);
    writeUninstallManifest(dir, manifestPath);

    const scriptPath = path.resolve(__dirname, 'installer', 'neutron.nsi');
    const definitions = {
      APP_DIR: dir,
      APP_NAME: appName,
      APP_VERSION: packageJSON.version,
      APP_FILE_VERSION: toFileVersion(packageJSON.version),
      TARGET_ARCH: targetArch,
      OUTPUT_FILE: outputPath,
      PROJECT_ROOT: path.resolve(__dirname, '..'),
      UNINSTALL_INCLUDE: manifestPath,
    };
    const args = ['/V4', '/WX', '/NOCD', '/INPUTCHARSET', 'UTF8'];
    for (const [name, value] of Object.entries(definitions)) args.push(`/D${name}=${value}`);
    args.push(scriptPath);

    const result = spawnSync(makeNsis, args, { encoding: 'utf8', windowsHide: true });
    if (result.stdout) process.stdout.write(result.stdout);
    if (result.stderr) process.stderr.write(result.stderr);
    if (result.error) throw result.error;
    if (result.status !== 0 || !fs.existsSync(outputPath)) {
      throw new Error(`NSIS kurucusu üretilemedi (makensis çıkış kodu ${result.status}).`);
    }
    return [outputPath];
  }
}

module.exports = MakerNsis;
module.exports.MakerNsis = MakerNsis;
